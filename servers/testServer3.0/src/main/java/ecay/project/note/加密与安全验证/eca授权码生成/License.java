package ecay.project.note.加密与安全验证.eca授权码生成;

public class License {

    private String deviceID;
    private String licenceApp;
    private String licenceEnd;

    public String getDeviceID() {
        return deviceID;
    }

    public void setDeviceID(String deviceID) {
        this.deviceID = deviceID;
    }

    public String getLicenceApp() {
        return licenceApp;
    }

    public void setLicenceApp(String licenceApp) {
        this.licenceApp = licenceApp;
    }

    public String getLicenceEnd() {
        return licenceEnd;
    }

    public void setLicenceEnd(String licenceEnd) {
        this.licenceEnd = licenceEnd;
    }
}
